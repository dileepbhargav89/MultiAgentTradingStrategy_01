class RiskLevel(str, Enum):
    """5-tier institutional portfolio drawdown risk levels + recovery mode."""
    GREEN = "GREEN"          # Normal trading: DD < 3.0%, 100% position sizing
    YELLOW = "YELLOW"        # Warning: 3.0% <= DD < 5.0%, 50% position sizing
    ORANGE = "ORANGE"        # High Risk: 5.0% <= DD < 8.0%, 25% position sizing
    RED = "RED"              # Severe Risk: 8.0% <= DD < 10.0%, 0% new risk (closing only)
    CRITICAL = "CRITICAL"    # Emergency: DD >= 10.0%, Emergency Flatten all positions
    RECOVERY = "RECOVERY"    # Post-drawdown recovery: max 25% sizing until HWM exceeded


