@dataclass
class StrategyGenome:
    """Immutable strategy DNA containing 8 core genes (alleles) and metadata."""
    strategy_id: str
    species: StrategySpecies
    entry_signal_threshold: float = 0.30       # Minimum directional confidence [0.15, 0.85]
    trend_filter_lookback: int = 50           # Moving average period for macro trend [10, 200]
    rsi_oversold_bound: float = 30.0          # Oversold bound for long entry [20.0, 40.0]
    rsi_overbought_bound: float = 70.0        # Overbought bound for short entry [60.0, 80.0]
    stop_loss_atr_mult: float = 1.8           # Stop loss distance in ATR multiples [1.0, 3.5]
    take_profit_atr_mult: float = 3.0         # Profit target distance in ATR multiples [1.5, 6.0]
    sentiment_filter_enabled: bool = True     # Whether to veto against extreme FGI / crowding
    generation: int = 0
    fitness_score: float = 0.0

    def to_dict(self) -> Dict[str, Any]:
        return {
            "strategy_id": self.strategy_id,
            "species": self.species.value if isinstance(self.species, StrategySpecies) else str(self.species),
            "entry_signal_threshold": round(self.entry_signal_threshold, 4),
            "trend_filter_lookback": int(self.trend_filter_lookback),
            "rsi_oversold_bound": round(self.rsi_oversold_bound, 2),
            "rsi_overbought_bound": round(self.rsi_overbought_bound, 2),
            "stop_loss_atr_mult": round(self.stop_loss_atr_mult, 2),
            "take_profit_atr_mult": round(self.take_profit_atr_mult, 2),
            "sentiment_filter_enabled": bool(self.sentiment_filter_enabled),
            "generation": int(self.generation),
            "fitness_score": round(self.fitness_score, 4),
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "StrategyGenome":
        species = data.get("species", StrategySpecies.MOMENTUM_TREND)
        if isinstance(species, str):
            species = StrategySpecies(species)
        return cls(
            strategy_id=str(data["strategy_id"]),
            species=species,
            entry_signal_threshold=float(data.get("entry_signal_threshold", 0.30)),
            trend_filter_lookback=int(data.get("trend_filter_lookback", 50)),
            rsi_oversold_bound=float(data.get("rsi_oversold_bound", 30.0)),
            rsi_overbought_bound=float(data.get("rsi_overbought_bound", 70.0)),
            stop_loss_atr_mult=float(data.get("stop_loss_atr_mult", 1.8)),
            take_profit_atr_mult=float(data.get("take_profit_atr_mult", 3.0)),
            sentiment_filter_enabled=bool(data.get("sentiment_filter_enabled", True)),
            generation=int(data.get("generation", 0)),
            fitness_score=float(data.get("fitness_score", 0.0)),
        )


