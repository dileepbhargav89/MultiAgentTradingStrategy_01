class PositioningQuadrant(str, Enum):
    """Classical derivatives positioning quadrant based on price and open interest changes."""
    LONG_ACCUMULATION = "LONG_ACCUMULATION"    # Price UP, OI UP (Aggressive new buyers)
    SHORT_COVERING = "SHORT_COVERING"          # Price UP, OI DOWN (Shorts buying back to exit)
    SHORT_ACCUMULATION = "SHORT_ACCUMULATION"  # Price DOWN, OI UP (Aggressive new sellers)
    LONG_LIQUIDATION = "LONG_LIQUIDATION"      # Price DOWN, OI DOWN (Longs forced out/liquidating)
    BALANCED = "BALANCED"                      # Neutral/Sideways


class CrowdingBias(str, Enum):
    """Aggregate market positioning crowding level."""
    CROWDED_LONG = "CROWDED_LONG"              # High risk of long squeeze
    BALANCED = "BALANCED"                      # Stable equilibrium
    CROWDED_SHORT = "CROWDED_SHORT"            # High risk of short squeeze


class VolatilityRegime(str, Enum):
    """Statistical market volatility regime."""
